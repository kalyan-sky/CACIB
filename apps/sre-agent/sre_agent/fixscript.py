"""A ready-to-run fix script for an incident: reviewed and run by an engineer, never by the agent.

    bash fix-INC-0001.sh              checks -> confirm -> fix -> verify
    bash fix-INC-0001.sh --check      read-only checks only
    bash fix-INC-0001.sh --rollback   the rollback steps (after confirmation)

Safety built in: it refuses to run against any cluster but the incident's, shows each command
before running it, asks before every change, and stops at the first failure.
"""

from __future__ import annotations

import re
import shlex

from .models import IncidentReport

_PLACEHOLDER = re.compile(r"<[A-Za-z][^<>]*>")


def _runnable(cmd: str) -> bool:
    """Lines with a leftover <placeholder> or prose become comments, so the script never misfires."""
    stripped = cmd.replace("</dev/null", "").replace("<<'EOF'", "")
    return not cmd.startswith("#") and not _PLACEHOLDER.search(stripped) and not cmd[:1].isupper()


def _block(cmd: str, explanation: str, change: bool) -> list[str]:
    if not _runnable(cmd):
        text = cmd.lstrip("# ")
        return [f"# {line}" for line in (text + (f" ({explanation})" if explanation else "")).splitlines()] + [
            f"manual {shlex.quote(text.splitlines()[0][:200])}"]
    return [f"# {explanation}" if explanation else "#", f"{'change' if change else 'run'} {shlex.quote(cmd)}"]


def build_script(report: IncidentReport, approval_status: str) -> str:
    ns = report.namespace or ""
    checks = [c for c in report.recommended_investigations]
    fix = report.commands_for_human_execution
    verify = report.verification_steps
    rollback = report.rollback_guidance
    out = [
        "#!/usr/bin/env bash",
        f"# Fix script for {report.incident_id}: {report.incident_type} in {report.cluster}/{ns or 'cluster-wide'}",
        f"# Root cause ({report.root_cause_status}, {round(report.root_cause_confidence * 100)}%): "
        + report.root_cause.replace("\n", " ")[:300],
        f"# Approval: {approval_status}. Generated by the read-only SRE agent, which did NOT run it.",
        "# Review every step. Usage: bash this-file [--check | --rollback]",
        "set -euo pipefail",
        f"CLUSTER={shlex.quote(report.cluster)}",
        'MODE="${1:-fix}"',
        'TTY="${FIX_TTY:-/dev/tty}"  # answers come from the terminal, even if this file is piped',
        "",
        "ctx=$(kubectl config current-context 2>/dev/null || true)",
        'if [[ "$ctx" != *"$CLUSTER"* ]]; then',
        '  echo "Refusing: kubectl context \\"$ctx\\" is not cluster $CLUSTER (kubectl config use-context ...)" >&2; exit 2',
        "fi",
        'run()    { printf "\\n\\033[1m$ %s\\033[0m\\n" "$1"; bash -o pipefail -c "$1"; }',
        'check()  { printf "\\n\\033[1m$ %s\\033[0m\\n" "$1"; bash -o pipefail -c "$1" || echo "(check failed; continuing)"; }',
        'change() { printf "\\n\\033[1;33mCHANGE:\\033[0m %s\\n" "$1"; read -rp "Run this change? [y/N] " a <"$TTY";'
        ' [ "$a" = y ] || { echo "Stopped before the change."; exit 1; }; bash -o pipefail -c "$1" <"$TTY"; }',
        'manual() { printf "\\n\\033[1;36mMANUAL STEP:\\033[0m %s\\n" "$1"; read -rp "Press Enter when done (Ctrl+C to stop) " _ <"$TTY"; }',
        "",
        f'echo "== {report.incident_id}: {report.incident_type} on $CLUSTER (namespace {ns or "-"}) =="',
        "",
        "# ---------------------------------------------------------------- 1. read-only checks",
    ]
    for c in checks:
        out += [line.replace("run ", "check ", 1) if line.startswith("run ") else line
                for line in _block(c.command, c.explanation, change=False)]
    out += ['[ "$MODE" = "--check" ] && { echo; echo "Checks done (no changes)."; exit 0; }', ""]
    if rollback:
        out.append("# ---------------------------------------------------------------- rollback (only with --rollback)")
        out.append('if [ "$MODE" = "--rollback" ]; then')
        for c in rollback:
            out += ["  " + line for line in _block(c.command, c.explanation, change=True)]
        out += ['  echo; echo "Rollback done."; exit 0', "fi", ""]
    if not fix:
        out += ['echo; echo "No fix is proposed: the root cause is not established. Use the checks above."', "exit 0"]
        return "\n".join(out) + "\n"
    out.append("# ---------------------------------------------------------------- 2. the fix (asks before each change)")
    for c in fix:
        out += _block(c.command, c.explanation, change=True)
    out += ["", "# ---------------------------------------------------------------- 3. verify"]
    for c in verify:
        out += [line.replace("run ", "check ", 1) if line.startswith("run ") else line
                for line in _block(c.command, c.explanation, change=False)]
    out += ["", f'echo; echo "Done. If it got worse: bash $0 --rollback. Then record the actions in the RCA '
                f'({report.incident_id})."']
    return "\n".join(out) + "\n"
